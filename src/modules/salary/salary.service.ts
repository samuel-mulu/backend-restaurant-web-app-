export interface ListSalaryFilters {
  staffId?: string;
  month?: string;
  year?: number;
  status?: "pending" | "paid";
  page?: number;
  limit?: number;
}

export const listSalaries = async (filters: ListSalaryFilters = {}) => {
  const { staffId, month, year, status, page = 1, limit = 50 } = filters;
  const query: any = {};

  if (staffId) {
    query.staffId = new Types.ObjectId(staffId);
  }

  if (month) {
    query.month = month;
  }

  if (year) {
    query.year = year;
  }

  if (status) {
    query.status = status;
  }

  const skip = (page - 1) * limit;

  const [salaries, total] = await Promise.all([
    Salary.find(query)
      .populate("staffId", "name email phone role")
      .populate("createdBy", "name email")
      .sort({ year: -1, month: -1, createdAt: -1 })
      .skip(skip)
      .limit(limit)
      .lean(),
    Salary.countDocuments(query),
  ]);

  return {
    salaries,
    pagination: {
      page,
      limit,
      total,
      pages: Math.ceil(total / limit),
    },
  };
};

