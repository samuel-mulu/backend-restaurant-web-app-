export const deletePayment = async (paymentId: string): Promise<void> => {
  const payment = await Payment.findById(paymentId);
  if (!payment) {
    throw { status: 404, message: "Payment not found" };
  }

  const salary = await Salary.findById(payment.salaryId);
  if (salary) {
    // Revert payment amount
    salary.totalPayments = Math.max(
      0,
      (salary.totalPayments || 0) - payment.amount
    );

    // Recalculate status
    const remainingBalance =
      (salary.netAmount || salary.amount) - salary.totalPayments;
    if (remainingBalance > 0) {
      salary.status = "pending";
    }

    await salary.save();
  }

  await Payment.findByIdAndDelete(paymentId);
};

/* ---------------------- AUTO-PAYMENT AND ROLLOVER ---------------------- */

/**
 * Auto-create payment when countdown reaches 0
 * This payment is created automatically but status remains "pending" until user manually records payment
 */
export const autoCreatePaymentOnDueDate = async (
  salaryId: string
): Promise<PaymentDoc | null> => {
  const salary = await Salary.findById(salaryId);
  if (!salary) {
    return null;
  }

  // Only create auto-payment if status is still pending
  if (salary.status !== "pending") {
    return null;
  }

  // Check if auto-payment already exists (prevent duplicates)
  const existingAutoPayment = await Payment.findOne({
    salaryId: new Types.ObjectId(salaryId),
    isAutoGenerated: true,
  });

  if (existingAutoPayment) {
    return existingAutoPayment;
  }

  // Calculate remaining balance
  const remainingBalance =
    (salary.netAmount || salary.amount) - (salary.totalPayments || 0);

  // Only create if there's a remaining balance
  if (remainingBalance <= 0) {
    return null;
  }

  // Create auto-payment for the full remaining balance
  const payment = await Payment.create({
    salaryId: new Types.ObjectId(salaryId),
    amount: remainingBalance,
    paymentDate: new Date(),
    paymentMethod: "other",
    remarks: "Auto-generated on due date",
    isAutoGenerated: true,
    // Use system user or the original creator as createdBy
    createdBy: salary.createdBy,
  });

  // Update salary totals but keep status as "pending"
  salary.totalPayments = (salary.totalPayments || 0) + remainingBalance;
  await salary.save();

  await payment.populate("createdBy", "name email");
  return payment;
};

/**
 * Auto-rollover dates to next month when payment date passes
 * Only updates dates, does not change status or create new salary record
 */
export const autoRolloverToNextMonth = async (
  salaryId: string
): Promise<boolean> => {
  const salary = await Salary.findById(salaryId);
  if (!salary) {
    return false;
  }

  // Only rollover if status is still pending
  if (salary.status !== "pending") {
    return false;
  }

  if (!salary.ethiopianPaymentDate) {
    return false;
  }

  // Get current Ethiopian date
  const currentEthDate = getCurrentEthiopianDate();
  const paymentDate = parseEthiopianDate(salary.ethiopianPaymentDate);

  // Check if payment date has passed (current date > payment date)
  const currentGreg = ethiopianToGregorian(currentEthDate);
  const paymentGreg = ethiopianToGregorian({
    year: currentEthDate.year,
    month: paymentDate.month,
    day: paymentDate.day,
  });

  // If payment date hasn't passed yet, don't rollover
  if (currentGreg <= paymentGreg) {
    return false;
  }

  // Update registered date to current date
  const newRegisteredDate = formatEthiopianDate(currentEthDate);
  salary.registeredDate = newRegisteredDate;

  // Update payment date to 1 month from current registered date
  const newPaymentEthDate = addEthiopianMonths(currentEthDate, 1);
  const newPaymentDateStr = formatEthiopianDate(newPaymentEthDate);
  salary.ethiopianPaymentDate = newPaymentDateStr;

  // Update Ethiopian month and year
  salary.ethiopianMonth = newPaymentEthDate.month;
  salary.ethiopianYear = newPaymentEthDate.year;

  // Convert new payment date to Gregorian and update related fields
  const newPaymentGreg = ethiopianToGregorian(newPaymentEthDate);
  salary.paymentDate = newPaymentGreg;
  salary.month = `${newPaymentGreg.getFullYear()}-${String(
    newPaymentGreg.getMonth() + 1
  ).padStart(2, "0")}`;
  salary.year = newPaymentGreg.getFullYear();

  await salary.save();
  return true;
};

/* ---------------------- COUNTDOWN CALCULATION ---------------------- */

export const calculateCountdown = async (salaryId: string) => {
  const salary = await Salary.findById(salaryId);
  if (!salary) {
    throw { status: 404, message: "Salary record not found" };
  }

  // Get current Gregorian date
  const now = new Date();
  
  // Use Gregorian payment date as primary if possible
  const paymentDateGreg = salary.paymentDate;
  
  // Calculate daysUntil using Gregorian dates
  const diffMs = paymentDateGreg.getTime() - now.getTime();
  const daysUntil = Math.max(0, Math.ceil(diffMs / (1000 * 60 * 60 * 24)));

  // Use Gregorian for primary countdown
  const nextPaymentGregorian = new Date(salary.paymentDate);
  if (now > nextPaymentGregorian && salary.status === "pending") {
    // If due date passed, rollover or show 0
    // Actually, autoRollover is called below
  }

  // Fallback to Ethiopian for backward compatibility if needed, 
  // but prioritize Gregorian for logic.
  const registeredDateEth = salary.registeredDate ? parseEthiopianDate(salary.registeredDate) : gregorianToEthiopian(salary.createdAt || new Date());
  const paymentDateEth = salary.ethiopianPaymentDate ? parseEthiopianDate(salary.ethiopianPaymentDate) : gregorianToEthiopian(salary.paymentDate);
  const currentEthDate = getCurrentEthiopianDate();

  // Calculate totalDays between registered and payment (Gregorian based)
  const registeredGregorian = salary.createdAt || new Date();
  const totalDaysDiffMs = nextPaymentGregorian.getTime() - registeredGregorian.getTime();
  const totalDays = Math.max(1, Math.ceil(totalDaysDiffMs / (1000 * 60 * 60 * 24)));

  // Auto-create payment if countdown reached 0 and status is pending
  if (daysUntil === 0 && salary.status === "pending") {
    await autoCreatePaymentOnDueDate(salaryId);
  }

  // Auto-rollover dates if payment date has passed and status is pending
  if (salary.status === "pending" && now > nextPaymentGregorian) {
    await autoRolloverToNextMonth(salaryId);

    // Reload salary to get updated dates if rollover occurred
    const updatedSalary = await Salary.findById(salaryId);
    if (updatedSalary && updatedSalary.paymentDate.getTime() !== salary.paymentDate.getTime()) {
      const updatedDiffMs = updatedSalary.paymentDate.getTime() - now.getTime();
      const updatedDaysUntil = Math.max(0, Math.ceil(updatedDiffMs / (1000 * 60 * 60 * 24)));
      
      const updatedTotalDaysDiffMs = updatedSalary.paymentDate.getTime() - (updatedSalary.createdAt || new Date()).getTime();
      const updatedTotalDays = Math.max(1, Math.ceil(updatedTotalDaysDiffMs / (1000 * 60 * 60 * 24)));

      return {
        daysUntil: updatedDaysUntil,
        totalDays: updatedTotalDays,
        nextPaymentDate: {
          ethiopian: updatedSalary.ethiopianPaymentDate || "",
          gregorian: updatedSalary.paymentDate.toISOString(),
        },
        registeredDate: updatedSalary.registeredDate || "",
        registeredDateGregorian: (updatedSalary.createdAt || new Date()).toISOString(),
      };
    }
  }

  return {
    daysUntil,
    totalDays, 
    nextPaymentDate: {
      ethiopian: salary.ethiopianPaymentDate || "",
      gregorian: nextPaymentGregorian.toISOString(),
    },
    registeredDate: salary.registeredDate || "",
    registeredDateGregorian: (salary.createdAt || new Date()).toISOString(),
  };
};

/* ---------------------- NET AMOUNT CALCULATION ---------------------- */

export const getNetAmount = async (salaryId: string): Promise<number> => {
  const salary = await Salary.findById(salaryId);
  if (!salary) {
    throw { status: 404, message: "Salary record not found" };
  }

  // Recalculate from withdrawals
  const withdrawals = await Withdrawal.find({
    salaryId: new Types.ObjectId(salaryId),
  }).lean();

  const totalWithdrawals = withdrawals.reduce((sum, w) => sum + w.amount, 0);

  const netAmount = salary.amount - totalWithdrawals;

  // Update salary record
  salary.totalWithdrawals = totalWithdrawals;
  salary.netAmount = netAmount;
  await salary.save();

  return netAmount;
};
